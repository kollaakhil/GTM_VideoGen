#!/usr/bin/env node
/**
 * Verifies the model registry against the providers' own model lists (free, key-less endpoints; no paid calls):
 *   OpenRouter  /api/v1/models and /api/v1/videos/models
 *   fal         api.fal.ai/v1/models (paged) and, with --schemas, each endpoint's OpenAPI schema
 *   Hugging Face router.huggingface.co/v1/models, plus huggingface.co/api/models/<repo> for open-weights repos
 *   Higgsfield  the MCP snapshot in catalog.ts (its list needs the account)
 *
 *   node scripts/verify-models.mjs                 check ids, prices, durations; exit 1 on any missing model
 *   node scripts/verify-models.mjs --schemas       also re-derive fal request knobs and report drift from the snapshot
 *   node scripts/verify-models.mjs --write-snapshot  rewrite src/lib/registry/fal-snapshot.ts from live fal schemas
 *   node scripts/verify-models.mjs --json          machine-readable output
 * Needs Node 22.18+ (runs the TypeScript catalog directly).
 */
import fs from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../src/lib/registry/", import.meta.url);
const { CATALOG, HIGGSFIELD_MCP_IDS, VERIFIED_AT } = await import(new URL("catalog.ts", root));
const { checkCatalog } = await import(new URL("verify.ts", root));
const { deriveKnobs } = await import(new URL("fal-knobs.ts", root));
const args = new Set(process.argv.slice(2));

const getJson = async (url) => {
  for (let attempt = 0; ; attempt++) {
    const res = await fetch(url, { headers: { "user-agent": "gtm-engine-verify-models" } });
    if (res.status === 429 && attempt < 10) { await new Promise((r) => setTimeout(r, 2500 * (attempt + 1))); continue; }
    if (!res.ok) throw new Error(`${url} -> ${res.status}`);
    return res.json();
  }
};

/** fal's catalog is rate limited: page through it slowly (about 15 requests) instead of asking per endpoint. */
async function falList() {
  const out = new Map();
  let cursor = "";
  for (let i = 0; i < 80; i++) {
    const j = await getJson(`https://api.fal.ai/v1/models?limit=100${cursor ? `&cursor=${cursor}` : ""}`);
    for (const m of j.models ?? []) out.set(m.endpoint_id, m.metadata?.status ?? "active");
    if (!j.has_more) break;
    cursor = j.next_cursor;
    await new Promise((r) => setTimeout(r, 1200));
  }
  return out;
}

const [or, orv, fal, hfr] = await Promise.all([
  getJson("https://openrouter.ai/api/v1/models"),
  getJson("https://openrouter.ai/api/v1/videos/models"),
  falList(),
  getJson("https://router.huggingface.co/v1/models"),
]);

const lists = {
  openrouter: new Map((or.data ?? []).map((m) => [m.id, { out: m.architecture?.output_modalities ?? [], inUsdPerM: Number(m.pricing?.prompt ?? 0) * 1e6, outUsdPerM: Number(m.pricing?.completion ?? 0) * 1e6 }])),
  orVideo: new Map((orv.data ?? []).map((m) => [m.id, { maxSeconds: m.supported_durations?.length ? Math.max(...m.supported_durations) : null, minSeconds: m.supported_durations?.length ? Math.min(...m.supported_durations.filter((d) => d > 0)) : null }])),
  fal,
  hfRouter: new Set((hfr.data ?? []).map((m) => m.id)),
  higgsfield: new Set(Object.values(HIGGSFIELD_MCP_IDS).flat()),
  hfRepos: new Set(),
};

const repos = [...new Set(CATALOG.map((e) => e.caps.hfRepo).filter(Boolean))];
await Promise.all(repos.map(async (r) => {
  const res = await fetch(`https://huggingface.co/api/models/${r}`, { headers: { "user-agent": "gtm-engine-verify-models" } });
  if (res.ok) lists.hfRepos.add(r);
}));

const { results, ok } = checkCatalog(CATALOG, lists, { repoCheck: true });

const falEndpoints = [...new Set(CATALOG.filter((e) => e.provider === "fal" && e.runnable).flatMap((e) => [e.id, e.fal?.t2v, e.fal?.edit].filter(Boolean)))];
const drifts = [];
if (args.has("--schemas") || args.has("--write-snapshot")) {
  const knobs = {};
  for (let i = 0; i < falEndpoints.length; i += 3) {
    await Promise.all(falEndpoints.slice(i, i + 3).map(async (ep) => {
      try {
        const k = deriveKnobs(await getJson(`https://fal.ai/api/openapi/queue/openapi.json?endpoint_id=${ep}`));
        if (k) knobs[ep] = k;
        else drifts.push(`${ep}: no usable input schema`);
      } catch (e) {
        drifts.push(`${ep}: ${e.message}`);
      }
    }));
  }
  const snapFile = new URL("fal-snapshot.ts", root);
  if (args.has("--write-snapshot")) {
    const sorted = Object.fromEntries(Object.entries(knobs).sort(([a], [b]) => a.localeCompare(b)));
    const body = `import type { FalKnobs } from "./fal-knobs.ts";\n\n/** Generated by \`node scripts/verify-models.mjs --write-snapshot\` from fal's OpenAPI schemas on ${VERIFIED_AT}. Do not edit by hand. */\nexport const FAL_KNOBS: Record<string, FalKnobs> = ${JSON.stringify(sorted, null, 1)};\n`;
    fs.writeFileSync(fileURLToPath(snapFile), body);
    console.log(`wrote ${Object.keys(sorted).length} fal endpoint snapshots`);
  } else {
    const { FAL_KNOBS } = await import(snapFile);
    for (const ep of falEndpoints) {
      if (!FAL_KNOBS[ep]) drifts.push(`${ep}: missing from fal-snapshot.ts (run --write-snapshot)`);
      else if (knobs[ep] && JSON.stringify(FAL_KNOBS[ep]) !== JSON.stringify(knobs[ep])) drifts.push(`${ep}: request schema changed since the snapshot`);
    }
  }
}

if (args.has("--json")) {
  console.log(JSON.stringify({ verifiedAt: VERIFIED_AT, ok: ok && !drifts.length, results, drifts }, null, 2));
} else {
  const by = (s) => results.filter((r) => r.status === s);
  for (const r of results) for (const m of [...r.errors.map((x) => `ERROR ${x}`), ...r.warnings.map((x) => `warn  ${x}`)]) console.log(`${r.id}: ${m}`);
  for (const d of drifts) console.log(`schema: ${d}`);
  console.log(`\n${CATALOG.length} models: ${by("verified").length} verified, ${by("local").length} local, ${by("unverified").length} unverified, ${by("missing").length} failing; ${repos.length} open-weights repos checked`);
}
process.exit(ok && !drifts.length ? 0 : 1);
